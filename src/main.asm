add_score_ax:
    add [score_lo], ax
    adc word [score_hi], 0
    cmp word [score_hi], 000Fh
    jb .done
    ja .cap
    cmp word [score_lo], 423Fh
    jbe .done
.cap:
    mov word [score_hi], 000Fh
    mov word [score_lo], 423Fh
.done:
    ret

award_extra_life:
    cmp byte [lives], 99
    jae .done
    inc byte [lives]
.done:
    ret

