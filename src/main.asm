spawn_brick_debris:
    push bx
    push cx
    push si
    mov cl, 4
    shl ax, cl
    shl dx, cl
    mov si, particles
    mov cx, 4
.loop:
    mov byte [si + 0], 18
    mov [si + 2], ax
    mov [si + 4], dx
    cmp cx, 4
    je .p0
    cmp cx, 3
    je .p1
    cmp cx, 2
    je .p2
    mov word [si + 6], 2
    jmp .next
.p0:
    mov word [si + 6], -2
    jmp .next
.p1:
    mov word [si + 6], -1
    jmp .next
.p2:
    mov word [si + 6], 1
.next:
    add si, PARTICLE_SZ
    loop .loop
    pop si
    pop cx
    pop bx
    ret

update_effects:
    cmp byte [popup_coin_timer], 0
    je .upd_particles
    dec byte [popup_coin_timer]
    sub word [popup_coin_y], 2

.upd_particles:
    mov si, particles
    mov cx, MAX_PARTICLES
.ploop:
    cmp byte [si + 0], 0
    je .pnext
    dec byte [si + 0]
    mov ax, [si + 6]
    add [si + 2], ax
    mov al, [si + 0]
    cmp al, 12
    ja .rise
    add word [si + 4], 3
    jmp .pnext
.rise:
    sub word [si + 4], 3
.pnext:
    add si, PARTICLE_SZ
    loop .ploop
    ret

; =========================================================================
; ENEMY AI & COLLISIONS (GOOMBAS & KOOPAS, MAX 8)
