; =========================================================================
; PROGRAM ENTRY POINT
; =========================================================================
start:
    cld
    cli
    push cs
    pop ds
    sti

    mov bx, 1000h
    mov ah, 4Ah
    int 21h
    jnc .mem_shrunk
    jmp main_loop.alloc_fail
.mem_shrunk:

    mov bx, 1000h
    mov ah, 48h
    int 21h
    jnc .mem_alloc_ok
    jmp main_loop.alloc_fail
.mem_alloc_ok:
    mov [buffer_seg], ax

    call install_keyboard
    call install_timer

    mov ax, 0013h
    int 10h

    call set_palette
    call load_font
    call init_new_game
    mov byte [game_state], ST_TITLE
    mov byte [menu_cursor], 0
    mov byte [controls_view], 0

; =========================================================================
; MAIN TIMER-DRIVEN GAME LOOP
; =========================================================================
main_loop:
    cmp byte [quit_flag], 1
    jne .dispatch
    jmp near exit_game

.dispatch:
    call wait_frame_tick

    mov al, [game_state]
    cmp al, ST_TITLE
    je .do_title
    cmp al, ST_PLAYING
    je .do_playing
    cmp al, ST_PAUSED
    je .do_paused
    cmp al, ST_DYING
    je .do_dying
    cmp al, ST_LIFELOST
    je .do_lifelost
    cmp al, ST_FLAGSLIDE
    je .do_flagslide
    cmp al, ST_WIN
    je .do_win
    cmp al, ST_GAMEOVER
    je .do_gameover
    jmp main_loop

.do_title:
    call update_title_state
    call render_title_screen
    jmp main_loop

.do_playing:
    call update_playing_state
    call render_play_frame
    jmp main_loop

.do_paused:
    call update_paused_state
    call render_paused_screen
    jmp main_loop

.do_dying:
    call update_dying_state
    call render_play_frame
    jmp main_loop

.do_lifelost:
    call update_lifelost_state
    call render_lifelost_screen
    jmp main_loop

.do_flagslide:
    call update_flagslide_state
    call render_play_frame
    jmp main_loop

.do_win:
    call update_win_state
    call render_win_screen
    jmp main_loop

.do_gameover:
    call update_gameover_state
    call render_gameover_screen
    jmp main_loop

.alloc_fail:
    mov ax, 0003h
    int 10h
    mov dx, str_alloc_err
    mov ah, 09h
    int 21h
    mov ax, 4C01h
    int 21h

exit_game:
    call restore_timer
    call restore_keyboard

    mov ax, 0003h
    int 10h

    mov ax, [buffer_seg]
    or ax, ax
    jz .dos_exit
    mov es, ax
    mov ah, 49h
    int 21h

.dos_exit:
    mov ax, 4C00h
    int 21h

; =========================================================================
; GAME INITIALIZATION & LEVEL RESET
; =========================================================================
start_player_death:
    mov byte [game_state], ST_DYING
    mov byte [power_state], 0
    mov byte [invuln_timer], 0
    mov word [player_vx], 0
    mov word [player_vy], -0480h
    mov byte [death_timer], 10
    ret

update_dying_state:
    cmp byte [death_timer], 0
    je .fall
    dec byte [death_timer]
    ret
.fall:
    add word [player_vy], GRAV_NORMAL
    cmp word [player_vy], MAX_VY_FALL
    jle .apply_y
    mov word [player_vy], MAX_VY_FALL
.apply_y:
    mov ax, [player_vy]
    add [player_y_frac], al
    mov al, ah
    cbw
    adc [player_y], ax

    cmp word [player_y], 208
    jl .done

    cmp byte [lives], 0
    je .to_gameover
    dec byte [lives]
    cmp byte [lives], 0
    je .to_gameover

    mov byte [game_state], ST_LIFELOST
    mov byte [state_timer], 42
    ret

.to_gameover:
    mov byte [game_state], ST_GAMEOVER
    call clear_edge_keys
.done:
    ret

update_lifelost_state:
    cmp byte [state_timer], 0
    je .respawn
    dec byte [state_timer]
    ret
.respawn:
    call reset_level_for_life
    mov byte [game_state], ST_PLAYING
    ret

update_playing_state:
    cmp byte [edge_p], 1
    jne .chk_esc
    mov byte [edge_p], 0
    mov byte [pause_cursor], 0
    mov byte [game_state], ST_PAUSED
    ret

.chk_esc:
    cmp byte [edge_esc], 1
    jne .run_systems
    mov byte [edge_esc], 0
    mov byte [game_state], ST_TITLE
    mov byte [menu_cursor], 0
    ret

.run_systems:
    call update_player
    cmp byte [game_state], ST_PLAYING
    jne .abort_frame

    call update_mushroom
    call update_enemies
    cmp byte [game_state], ST_PLAYING
    jne .abort_frame

    call update_effects
    call update_camera
    call update_level_timer
.abort_frame:
    ret

