set_palette:
    mov dx, 03C8h
    xor al, al
    out dx, al
    inc dx
    mov si, palette_data
    mov cx, PAL_TOTAL_COLORS * 3
.out_loop:
    lodsb
    shr al, 1
    shr al, 1
    out dx, al
    loop .out_loop
    ret

load_font:
    push ax
    push bx
    push es
    mov ax, 1130h
    mov bh, 03h
    int 10h
    mov [font_seg], es
    mov [font_off], bp
    pop es
    pop bx
    pop ax
    ret

